#!/usr/bin/env python3
"""Prepare Ibex synthesis corrections without changing the submodule."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def prepare():
    source = ROOT / "src/vendor/ibex/rtl/ibex_top.sv"
    text = source.read_text()
    # A variable declaration initializer runs once at time zero. The upstream
    # unused-input sink intends a continuous expression, not initial state.
    old = "logic unused_scramble_inputs ="
    if text.count(old) == 1:
        text = text.replace(old, "wire unused_scramble_inputs =", 1)
    elif "wire unused_scramble_inputs =" not in text:
        raise RuntimeError("Ibex top changed: review the unused_scramble_inputs correction")
    target = ROOT / "src/generated/ibex_top.sv"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("// Generated by scripts/prepare_ibex.py; do not edit.\n" + text)

    # With M disabled, upstream leaves the optional unit's outputs undriven.
    # Although their paths optimize away, LibreLane's earlier Yosys check sees
    # the two 33-bit operand buses before that optimization (66 diagnostics).
    ex_text = (ROOT / "src/vendor/ibex/rtl/ibex_ex_block.sv").read_text()
    marker = "  end\n\n  // Multiplier/divider may require multiple cycles."
    if ex_text.count(marker) != 1:
        raise RuntimeError("Ibex execute block changed: review the RV32MNone tie-offs")
    replacement = """  end else if (RV32M == RV32MNone) begin : gen_multdiv_none
    // Defined defaults for the absent multiplier/divider. multdiv_sel is zero.
    assign multdiv_alu_operand_a = '0;
    assign multdiv_alu_operand_b = '0;
    assign multdiv_result        = '0;
    assign multdiv_valid         = 1'b0;
    assign multdiv_imd_val_d     = '{default: '0};
    assign multdiv_imd_val_we    = '0;
  end

  // Multiplier/divider may require multiple cycles."""
    ex_target = target.parent / "ibex_ex_block.sv"
    ex_target.write_text("// Generated by scripts/prepare_ibex.py; do not edit.\n" +
                         ex_text.replace(marker, replacement, 1))
    return target


if __name__ == "__main__":
    print(prepare())
